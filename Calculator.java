class Calculator{

      public static void main(String [] args){

      
       int a = 10;
       int b = 20;

       char tasks = '/';

     switch(tasks) {

     case '+': {

     System.out.println( a+ "+" +b+ "=" + (a+b));

    }break;
     case '-': {

     System.out.println( a+ "-" +b+ "=" + (a-b));

    }break;
     case '*': {

     System.out.println( a+ "*" +b+ "=" + (a*b));

    }break;
     case '/': {

     System.out.println( a+ "/" +b+ "=" + (a/b));

    }break;
     case '%': {

     System.out.println( a+ "%" +b+ "=" + (a%b));

    }break;
    default: {

     System.out.println("Invalid task");
}





}





}



}